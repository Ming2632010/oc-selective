import type { EarlyMathDifficulty, EarlyMathKind, EarlyMathSkill, MathStimulus } from './early-math';

type Draft = {
  slug: string;
  unitId: number;
  skill: EarlyMathSkill;
  kind?: EarlyMathKind;
  title: string;
  stem: string;
  stimulus?: MathStimulus;
  options?: string[];
  correctIndex?: number;
  accepted?: string[];
  explanation: string;
  parentPrompt: string;
  difficulty?: EarlyMathDifficulty;
};

function choice(draft: Draft & { options: string[]; correctIndex: number }): Draft {
  return { kind: 'choice', ...draft };
}

function count(draft: Draft & { accepted: string[] }): Draft {
  return { kind: 'count', ...draft };
}

function yesNo(draft: Draft & { yes: boolean }): Draft {
  return {
    kind: 'true_false',
    options: ['Yes', 'No'],
    correctIndex: draft.yes ? 0 : 1,
    ...draft,
  };
}

